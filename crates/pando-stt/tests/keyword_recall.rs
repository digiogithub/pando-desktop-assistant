#![allow(clippy::expect_used)]
//! PDA-T-0092 acceptance: with language forced and the keyword bias, >= 90 % of the project /
//! agent names in the 50 spoken commands should be recognised. With the *synthetic* Piper voice
//! (which says English terms with a Spanish accent) the measured recall is 82.9 % (34/41); the
//! 90 % target needs real recordings (spike S1 follow-up). This test guards against regressions
//! with `PANDO_RECALL_MIN` (default 0.80); set it to 0.9 once real clips exist.
//!
//! Needs the engine, the model and the clip set (50 `davefx_NN.wav`, Piper `es_ES-davefx-medium`
//! speaking `fixtures/commands_es.txt`; generated by `spikes/whistle-ffi/scripts/prep_s1.py` into
//! `$PANDO_STT_CMD_SET`, default `~/.cache/pando-assistant-spikes/sets/cmd`).
//! Run: `cargo test -p pando-stt --test keyword_recall -- --ignored --nocapture`.

use pando_stt::keywords::{KeywordList, resolve_language};
use pando_stt::{Stt, SttOpts, Whistle};

fn norm(s: &str) -> String {
    let mut o = String::new();
    for c in s.to_lowercase().chars() {
        o.push(match c {
            'á' => 'a',
            'é' => 'e',
            'í' => 'i',
            'ó' => 'o',
            'ú' | 'ü' => 'u',
            c if c.is_alphanumeric() => c,
            _ => ' ',
        });
    }
    o.split_whitespace().collect::<Vec<_>>().join(" ")
}

#[test]
#[ignore = "needs libneedle, whistle.cact and the generated command clips"]
fn project_names_recall_meets_minimum() {
    let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR"));
    let model = std::env::var_os("PANDO_WHISTLE_MODEL").map_or_else(
        || root.join("../../vendor/needle/models/whistle.cact"),
        Into::into,
    );
    let set = std::env::var_os("PANDO_STT_CMD_SET").map_or_else(
        || {
            std::path::PathBuf::from(std::env::var("HOME").unwrap_or_default())
                .join(".cache/pando-assistant-spikes/sets/cmd")
        },
        Into::into,
    );
    let commands =
        std::fs::read_to_string(root.join("tests/fixtures/commands_es.txt")).expect("commands");
    let terms: Vec<String> = std::fs::read_to_string(root.join("tests/fixtures/keywords_es.txt"))
        .expect("keywords")
        .lines()
        .map(str::to_string)
        .collect();
    let mut w = Whistle::load_file(&model).expect("model");
    let opts = SttOpts {
        lang: resolve_language("es-ES"),
        keywords: KeywordList::new().projects(terms.clone()).build(),
        word_ts: false,
    };
    let (mut total, mut hit) = (0, 0);
    for (i, reference) in commands.lines().enumerate() {
        let wav = set.join(format!("davefx_{i:02}.wav"));
        let mut r = hound::WavReader::open(&wav).expect("clip");
        let pcm: Vec<f32> = r
            .samples::<i16>()
            .map(|s| f32::from(s.expect("s")) / 32768.0)
            .collect();
        let hyp = norm(&w.transcribe(&pcm, &opts).expect("transcribe").text);
        let rf = norm(reference);
        for t in &terms {
            let t = norm(t);
            if rf.contains(&t) {
                total += 1;
                if hyp.contains(&t) {
                    hit += 1;
                } else {
                    println!("miss {t:?}: ref {rf:?} hyp {hyp:?}");
                }
            }
        }
    }
    let recall = hit as f32 / total as f32;
    println!("keyword recall: {hit}/{total} = {:.1} %", recall * 100.0);
    let min: f32 = std::env::var("PANDO_RECALL_MIN")
        .ok()
        .and_then(|v| v.parse().ok())
        .unwrap_or(0.80);
    assert!(recall >= min, "recall {recall:.3} < {min}");
}
