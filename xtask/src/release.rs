//! Release tooling: `notice`, `check-nm`, `source-bundle` and `bundle` (PDA-T-0151, PDA-T-0143).
//!
//! - `notice`: per-binary third-party Rust inventories (`cargo deny list`), written to
//!   `dist/legal/THIRD-PARTY-<bin>.md`; also runs `cargo deny check licenses` on each graph.
//! - `check-nm`: ADR 0007 release gate, no `espeak_` symbols in `pando-assistant` or `pando-stt`.
//! - `source-bundle`: the GPL-3 Corresponding Source of `pando-tts` (see `packaging/SOURCE-OFFER.md`).
//! - `bundle`: build release binaries, run the gates, stage resources and call `cargo packager`.

use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

use anyhow::{Context, Result, bail};
use serde_json::Value;

/// (binary, crate directory) pairs that make up the product.
const BINARIES: [(&str, &str); 3] = [
    ("pando-assistant", "crates/app"),
    ("pando-stt", "crates/pando-stt"),
    ("pando-tts", "crates/pando-tts"),
];

/// Binaries that must stay free of espeak-ng (ADR 0007).
const ESPEAK_FREE: [&str; 2] = ["pando-assistant", "pando-stt"];

fn root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("..")
}

fn run(cmd: &mut Command) -> Result<()> {
    let status = cmd.status().with_context(|| format!("spawning {cmd:?}"))?;
    if !status.success() {
        bail!("{cmd:?} failed with {status}");
    }
    Ok(())
}

/// Number of defined `espeak_*` symbols in a binary (`nm`).
pub fn espeak_symbols(bin: &Path) -> Result<usize> {
    let out = Command::new("nm")
        .arg(bin)
        .output()
        .context("running `nm` (binutils)")?;
    if !out.status.success() {
        bail!(
            "nm {} failed (stripped binary? run the check before stripping): {}",
            bin.display(),
            String::from_utf8_lossy(&out.stderr).trim()
        );
    }
    Ok(count_espeak(&String::from_utf8_lossy(&out.stdout)))
}

/// Count `nm` lines naming an `espeak_` symbol.
fn count_espeak(nm_output: &str) -> usize {
    nm_output
        .lines()
        .filter(|l| {
            l.split_whitespace()
                .last()
                .is_some_and(|s| s.contains("espeak_"))
        })
        .count()
}

/// `cargo xtask check-nm [dir]`: gate on the release binaries in `dir` (default `target/release`).
pub fn check_nm(args: &[String]) -> Result<bool> {
    let dir = args
        .first()
        .map_or_else(|| root().join("target/release"), PathBuf::from);
    let mut ok = true;
    for (bin, _) in BINARIES {
        let path = dir.join(bin);
        if !path.exists() {
            println!("check-nm: {bin}: not built, skipped");
            continue;
        }
        let n = espeak_symbols(&path)?;
        if ESPEAK_FREE.contains(&bin) {
            if n == 0 {
                println!("check-nm: {bin}: 0 espeak_ symbols (ok)");
            } else {
                eprintln!("check-nm: {bin}: {n} espeak_ symbols; it must contain none (ADR 0007)");
                ok = false;
            }
        } else {
            println!("check-nm: {bin}: {n} espeak_ symbols (GPL-3 worker, expected)");
        }
    }
    Ok(ok)
}

/// One markdown inventory for a crate graph from `cargo deny list -f json`.
fn inventory(manifest: &str, bin: &str) -> Result<String> {
    let out = Command::new("cargo")
        .args([
            "deny",
            "--manifest-path",
            manifest,
            "list",
            "-l",
            "license",
            "-f",
            "json",
        ])
        .current_dir(root())
        .output()
        .context("running `cargo deny` (cargo install cargo-deny)")?;
    if !out.status.success() {
        bail!(
            "cargo deny list failed: {}",
            String::from_utf8_lossy(&out.stderr)
        );
    }
    let v: Value = serde_json::from_slice(&out.stdout).context("parsing cargo deny json")?;
    let mut s = format!(
        "# Third-party Rust crates linked into `{bin}`\n\nGenerated by `cargo xtask notice` \
         from the resolved dependency graph of `{manifest}`. A crate with several licences \
         appears under each alternative of its SPDX expression; the full licence texts are in \
         `licenses/` and in each crate's source.\n\nNon-crate components (libneedle, \
         sherpa-onnx, ONNX Runtime, espeak-ng, models, voices, fonts) are in `NOTICE`.\n"
    );
    let empty = Vec::new();
    for entry in v["licenses"].as_array().unwrap_or(&empty) {
        let lic = entry[0].as_str().unwrap_or("?");
        let crates = entry[1].as_array().unwrap_or(&empty);
        let _ = write!(s, "\n## {lic} ({})\n\n", crates.len());
        let mut names: Vec<&str> = crates
            .iter()
            .filter_map(|c| c.as_str())
            .filter_map(|c| c.split(" registry+").next())
            .collect();
        names.sort_unstable();
        for n in names {
            let _ = writeln!(s, "- {n}");
        }
    }
    Ok(s)
}

/// `cargo xtask notice`: write `dist/legal/` (inventories, NOTICE, licences) and gate licences.
pub fn notice() -> Result<bool> {
    let out = root().join("dist/legal");
    fs::create_dir_all(out.join("licenses"))?;
    let mut ok = true;
    for (bin, dir) in BINARIES {
        let manifest = format!("{dir}/Cargo.toml");
        fs::write(
            out.join(format!("THIRD-PARTY-{bin}.md")),
            inventory(&manifest, bin)?,
        )?;
        let status = Command::new("cargo")
            .args(["deny", "--manifest-path", &manifest, "check", "licenses"])
            .current_dir(root())
            .status()?;
        if !status.success() {
            eprintln!("notice: cargo deny check licenses failed for {bin}");
            ok = false;
        }
        println!("notice: THIRD-PARTY-{bin}.md written");
    }
    copy_legal_static(&out)?;
    Ok(ok)
}

fn copy_legal_static(out: &Path) -> Result<()> {
    let r = root();
    for f in ["NOTICE", "SOURCE-OFFER.md"] {
        fs::copy(r.join("packaging").join(f), out.join(f))?;
    }
    for entry in fs::read_dir(r.join("packaging/licenses"))? {
        let p = entry?.path();
        if let Some(n) = p.file_name() {
            fs::copy(&p, out.join("licenses").join(n))?;
        }
    }
    for entry in fs::read_dir(r.join("crates/app/assets/fonts"))? {
        let p = entry?.path();
        if p.extension().is_some_and(|e| e == "txt")
            && let Some(n) = p.file_name()
        {
            fs::copy(&p, out.join("licenses").join(n))?;
        }
    }
    fs::copy(r.join("crates/app/NOTICE"), out.join("NOTICE-app-crate"))?;
    Ok(())
}

/// `cargo xtask source-bundle`: GPL-3 Corresponding Source of `pando-tts`.
pub fn source_bundle() -> Result<bool> {
    let r = root();
    let version = env!("CARGO_PKG_VERSION");
    let dist = r.join("dist");
    fs::create_dir_all(&dist)?;
    let tar = dist.join(format!(
        "pando-assistant-{version}-corresponding-source.tar.gz"
    ));
    let sources = dist.join("SOURCES.txt");
    let commit = Command::new("git")
        .args(["rev-parse", "HEAD"])
        .current_dir(&r)
        .output()?;
    let commit = String::from_utf8_lossy(&commit.stdout).trim().to_owned();
    fs::write(
        &sources,
        format!(
            "pando-assistant commit {commit}\n\
             sherpa-onnx v1.13.8 https://github.com/k2-fsa/sherpa-onnx (tag v1.13.8)\n\
             espeak-ng (k2-fsa fork) and piper-phonemize: pinned by sherpa-onnx cmake/espeak-ng-for-piper.cmake and cmake/piper-phonemize.cmake at that tag\n\
             onnxruntime: pinned by sherpa-onnx cmake/onnxruntime.cmake at that tag\n\
             build: cargo build --release -p pando-tts (Cargo.lock included)\n"
        ),
    )?;
    // git archive of the tracked tree at HEAD, then SOURCES.txt appended via a second tar pass.
    let plain = dist.join("source.tar");
    run(Command::new("git")
        .args(["archive", "--format=tar", "-o"])
        .arg(&plain)
        .arg("HEAD")
        .current_dir(&r))?;
    run(Command::new("tar")
        .arg("--append")
        .arg("-f")
        .arg(&plain)
        .arg("-C")
        .arg(&dist)
        .arg("SOURCES.txt")
        .current_dir(&r))?;
    run(Command::new("gzip").arg("-f").arg(&plain).current_dir(&r))?;
    fs::rename(dist.join("source.tar.gz"), &tar)?;
    println!("source-bundle: {}", tar.display());
    Ok(true)
}

/// `cargo xtask bundle [--no-build] [--formats deb,appimage]`.
pub fn bundle(args: &[String]) -> Result<bool> {
    let r = root();
    let no_build = args.iter().any(|a| a == "--no-build");
    let formats = args
        .iter()
        .position(|a| a == "--formats")
        .and_then(|i| args.get(i + 1))
        .map_or("deb,appimage", String::as_str);
    if !no_build {
        run(Command::new("cargo")
            .args([
                "build",
                "--release",
                "-p",
                "app",
                "-p",
                "pando-stt",
                "-p",
                "pando-tts",
            ])
            .current_dir(&r))?;
    }
    if !check_nm(&[])? {
        return Ok(false);
    }
    if !notice()? {
        return Ok(false);
    }
    source_bundle()?;
    // Resources staged next to the packager config (paths in packaging/Packager.toml).
    let stage = r.join("dist/stage");
    let _ = fs::remove_dir_all(&stage);
    fs::create_dir_all(stage.join("models"))?;
    let whistle = r.join("vendor/needle/models/whistle.cact");
    if whistle.exists() {
        fs::copy(&whistle, stage.join("models/whistle.cact"))?;
    } else {
        eprintln!(
            "bundle: warning: {} missing (scripts/fetch-needle.sh --model)",
            whistle.display()
        );
    }
    let voices = r.join("vendor/voices");
    if voices.is_dir() {
        copy_dir(&voices, &stage.join("models/voices"))?;
    } else {
        eprintln!("bundle: warning: vendor/voices missing, package ships without a TTS voice");
    }
    copy_dir(&r.join("dist/legal"), &stage.join("legal"))?;
    run(Command::new("cargo")
        .args([
            "packager",
            "--release",
            "--config",
            "packaging/Packager.toml",
            "--formats",
            formats,
        ])
        .current_dir(&r))?;
    Ok(true)
}

fn copy_dir(from: &Path, to: &Path) -> Result<()> {
    fs::create_dir_all(to)?;
    for entry in fs::read_dir(from)? {
        let entry = entry?;
        let dst = to.join(entry.file_name());
        if entry.file_type()?.is_dir() {
            copy_dir(&entry.path(), &dst)?;
        } else {
            fs::copy(entry.path(), dst)?;
        }
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::count_espeak;

    #[test]
    fn counts_only_espeak_symbols() {
        let nm = "0000 T espeak_Synth\n0001 t _ZN6espeak_foo\n0002 T main\n0003 U memcpy\n";
        assert_eq!(count_espeak(nm), 2);
        assert_eq!(count_espeak("0000 T main\n"), 0);
    }
}
